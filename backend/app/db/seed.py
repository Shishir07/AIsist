# ─── Seed functions ───────────────────────────────────────────────────────────

async def seed_ingredient_db(db: AsyncSession):
    result = await db.execute(select(IngredientDB).limit(1))
    if result.scalar_one_or_none() is not None:
        return  # already seeded

    logger.info("Seeding IngredientDB...")
    for item in INGREDIENTS:
        ingredient = IngredientDB(
            name=item["name"],
            aliases=json.dumps(item.get("aliases", [])),
            primary_nutrient=item["primary_nutrient"],
            category=item["category"],
            common_units=json.dumps(item.get("common_units", [])),
            is_custom=False,
        )
        db.add(ingredient)
    await db.commit()
    logger.info(f"Seeded {len(INGREDIENTS)} ingredients")


async def seed_recipes(db: AsyncSession):
    result = await db.execute(select(Recipe).limit(1))
    if result.scalar_one_or_none() is not None:
        return  # already seeded

    logger.info("Seeding RecipeDB...")
    for item in RECIPES:
        recipe = Recipe(
            name=item["name"],
            cuisine_type=item["cuisine_type"],
            description=item.get("description"),
            instructions=item.get("instructions"),
            prep_time_minutes=item.get("prep_time_minutes", 30),
            serves=item.get("serves", 4),
            ingredients=json.dumps(item.get("ingredients", [])),
            tags=json.dumps(item.get("tags", [])),
            is_builtin=True,
        )
        db.add(recipe)
    await db.commit()
    logger.info(f"Seeded {len(RECIPES)} recipes")


async def run_seeds(db: AsyncSession):
    await seed_ingredient_db(db)
    await seed_recipes(db)
